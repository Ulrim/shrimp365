// 엔진 3(출하 윈도우)의 고정 숫자. **값만 옮겨 적지 않고 출처와 근거를 함께
// 적는다** — lib/growth/constants.ts · lib/profitability/constants.ts ·
// lib/pricing/constants.ts 와 같은 방식이다.
//
// 여기 있는 것은 **기본값**이고 전부 호출자가 인자로 바꿀 수 있다. 특히 일별
// 생존율은 농가·시기마다 다르다 — 아래 주석을 읽고 쓸 것.

/**
 * 천황수산 2024 코호트의 사이클 생존율. 입식 1,200,000마리 → 출하
 * 537,562마리 = **44.8%**.
 *
 * **출처: 천황수산 실데이터 2024-03-12 입식 ~ 2024-12-05, 엔진 2 가 재현한다
 * (lib/profitability/performance.ts).** 다만 이 분모는 사람이 ManagementNotes
 * 를 읽어 복원한 파생 라벨이고 원본 데이터의 사실이 아니다
 * (dataset-assessment 4-7·4-8). 그 사실은 엔진 2 의
 * `cycle_boundary_derived_label` 로 나간다.
 */
export const CHEONHWANG_CYCLE_SURVIVAL_RATE = 0.448

/** 같은 코호트의 사육 일수. 2024-03-12 ~ 2024-12-05 = 268일. */
export const CHEONHWANG_CYCLE_DAYS = 268

/**
 * **기본 일별 생존율 — 0.448^(1/268) ≈ 0.99701, 즉 하루 약 0.30% 폐사.**
 *
 * ── 이 값을 기본값으로 두는 이유, 그리고 두지 않은 다른 값 ───────────────
 * 엔진 3 에서 가장 틀리기 쉬운 자리가 폐사다. 더 키우면 개체가 커지는 것만
 * 계산하고 마리수가 줄는 것을 빼먹으면 엔진이 **항상 "더 키우라"** 고 말한다.
 * 그 방향으로 틀리는 것이 농가에게 가장 비싸다.
 *
 * 그래서 호출자가 생존율을 안 넘겼을 때 **0% 폐사로 가정하지 않는다.** 대신
 * 우리가 가진 유일한 실측 코호트에서 환산한 값을 쓰고, 가정이라는 사실을
 * `harvest_daily_survival_default` 와 엔진 2 의 `survival_rate_assumed` 로
 * 반환값에 담아 보낸다.
 *
 * ── 이 값은 농가·시기마다 다르다 ────────────────────────────────────────
 * 268일 평균을 지수로 균등 배분한 수이고, **실제 폐사는 균등하지 않다.**
 * 입식 직후와 수질 사고 때 몰리고, 출하 직전 구간은 보통 이보다 낮다.
 * 코호트 평균을 출하 직전 2주에 그대로 적용하면 폐사를 과대평가하는 쪽이다 —
 * 즉 이 기본값의 편향 방향은 "덜 키우자" 이고, 그쪽이 안전한 방향이다.
 * **농가 실측이 있으면 반드시 인자로 넘길 것.**
 */
export const DEFAULT_DAILY_SURVIVAL_RATE = Math.pow(
  CHEONHWANG_CYCLE_SURVIVAL_RATE,
  1 / CHEONHWANG_CYCLE_DAYS,
)

/** 후보 시점의 기본 간격(일). 농가가 출하를 주 단위로 잡는다. */
export const DEFAULT_STEP_DAYS = 7

/**
 * 기본 지평(일). 4주.
 *
 * 지평을 넓게 두면 이익 최대가 지평 안쪽에 들어와 보기 좋지만, 엔진 1 의
 * 예측 거리가 길어질수록 오차가 커지고 수온 전망도 멀어진다. 최대가 지평의
 * 마지막 후보에 걸리면 **지평 밖에 최적이 있을 수 있다**는 사실을
 * `harvest_horizon_truncated` 로 알린다 — 지평을 자동으로 늘리지 않는다.
 */
export const DEFAULT_HORIZON_DAYS = 28

/**
 * 예측 개체중이 고정 상한(Winf)의 몇 배에 닿으면 경고할 것인가.
 *
 * 엔진 1 의 Winf 는 **적합하지 않는 고정 가정**이다(설계 규칙 1). 후보 시점의
 * 예측이 상한에 붙어 있으면 그 구간의 "더 키우면 커진다" 는 데이터가 아니라
 * 그 가정이 만든 수다. 0.99 는 상한의 1% 안쪽을 뜻한다.
 */
export const WINF_CEILING_RATIO = 0.99

/**
 * 일별 생존율 뒤집힘 탐색의 기본 구간.
 *
 * 하루 50% 폐사는 현실의 농가가 아니지만, **구간 양 끝에서 부호가 갈리는 것을
 * 보장하는 괄호**로서 넓게 잡는다. 좁게 잡으면 뒤집힘이 구간 밖에 있을 때
 * 「없다」로 보고하게 된다.
 */
export const DEFAULT_FLIP_SEARCH_RANGE = { min: 0.5, max: 1 } as const

/** 이분법 반복 수. 60회면 배정밀도 한계까지 좁혀진다. */
export const FLIP_SEARCH_ITERATIONS = 60
