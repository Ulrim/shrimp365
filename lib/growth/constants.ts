// 엔진 1(생육 성장곡선)의 고정 숫자. 근거는 전부
// docs/plans/tips-2026-dataset-assessment.md 2절에 있다 — 여기에 숫자만 옮겨
// 적고 근거를 적지 않으면 나중에 아무도 왜 이 값인지 확인하지 못한다.

// 적산수온 시간축의 기준온도(℃). 0 은 기준온도를 차감하지 않는다는 뜻이다.
//
// Powell(2020)이 흰다리새우에 쓴 TGC(thermal-unit growth coefficient)는 수온의
// 단순 누적합 Σ(T × 일수)이고 기준온도를 빼지 않는다. 작물학의 Σ(T − T_base) 형
// degree-day 와 같은 개념이 아니다. 처음 설계서는 base 15 ℃ 였는데, 흰다리새우용
// 으로 공표된 기준온도가 없어 그 15 는 우리가 지어낸 숫자였다. 0·5·10·15·18 을
// 전부 돌려 권고 처방의 홀드아웃 MAE 가 다섯 경우 모두 같음을 확인했으므로,
// 성능이 같을 때는 문헌이 쓰는 형태를 쓴다(설계 규칙 4).
//
// **튜닝 금지.** 2-1 이 평균 R² 의 폭이 0.001 미만임을 보였다. 나아질 것 같은
// 외형을 가진 파라미터라 손대기 쉽지만 실제로 아무 효과가 없다.
export const BASE_TEMP_C = 0

// 성장 구간이 갈리는 경계(g). Powell(2020, Aquaculture Research, DOI
// 10.1111/are.14391)이 흰다리새우 성장 궤적에서 7.5 g 을 경계로 두 패턴이
// 뚜렷이 갈린다고 보고했다(stanza break). 출하 판단에 필요한 구간도 이쪽이다.
//
// **단독으로는 효과가 없다.** 7.5 g 이상만 쓰고 Winf 를 자유로 두면 홀드아웃
// MAE 15.51 g 으로 네 처방 중 가장 나쁘다. DEFAULT_WINF_G 고정과 반드시 같이
// 쓴다(설계 규칙 3).
export const STANZA_BREAK_G = 7.5

// 고정할 상한중량(g). 우리 데이터에서 7.5 g 이상 구간의 홀드아웃 MAE 가 가장
// 낮았던 값이다(0.90 g, 수조 5개).
//
// **자유 파라미터로 두지 않는다**(설계 규칙 1). Gompertz 의 Winf 는 곡선이 꺾여
// 평평해지는 높이인데, 관측 구간이 아직 꺾이기 전이면 상한을 어디로 잡아도 앞
// 구간이 똑같이 잘 맞아서 적합기가 아무 값이나 고른다. 그래서 R² 0.99 와 홀드아웃
// MAE 32 g 이 동시에 나온다 — 수조 2 는 19.7 g 을 91.8 g 으로 예측했다.
//
// 값 자체는 2차적이다. 전 구간 적합에서는 25~40 g 어디로 잡아도 2.9~3.4 g 범위였다
// — **고정한다는 사실이 효과의 거의 전부다.** 품종·농가가 달라지면 호출자가 인자로
// 바꾸면 되지만, 자유 적합 경로는 이 모듈에 아예 없다.
export const DEFAULT_WINF_G = 25

// 적합에 필요한 최소 표본 수. Winf 를 고정하면 자유 파라미터가 b·k 두 개라
// 수학적으로는 2점으로 직선이 결정되지만, 2점은 언제나 잔차 0 이라 적합이 되는지
// 알 수 없다. 참조 구현(scripts/analysis/growth_curve_feasibility.py)의
// MIN_TRAIN_FIXED 와 같은 3 을 쓴다.
export const MIN_FIT_SAMPLES = 3
