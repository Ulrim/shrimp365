# 부록 도면 페이지(A3 가로)에서 도면이 쓸 수 있는 영역 (여백 10 + 캡션 여유)
# A4 로 앉히면 원본 A2 시트가 0.42 배로 줄어 주기 글자가 1.4 mm 가 된다 — 읽히지 않는다.
LAND_W, LAND_H = 397.0, 262.0


def svg(name, cap):
    """도면 SVG 를 A4 가로 한 장에 통째로 앉힌다.

    원본 폭·높이(mm)로 종횡비를 잡아 폭을 mm 로 못박는다. width:100% 로 두면
    A2 비율(1.414)이 세로로 넘쳐 캡션이 다음 장으로 밀려난다.
    본문은 A4 세로, 이 페이지들만 A3 가로다."""
    p = os.path.join(ENC, "svg", name)
    s = open(p, encoding="utf-8").read()
    m = re.search(r'width="([\d.]+)mm"\s+height="([\d.]+)mm"', s)
    w0, h0 = (float(m.group(1)), float(m.group(2))) if m else (LAND_W, LAND_H)
    w = min(LAND_W, LAND_H * w0 / h0)
    s = re.sub(r'width="[^"]*mm"\s+height="[^"]*mm"',
               'width="%.1fmm"' % w, s, count=1)
    return ('<figure class="dwg"><div class="svgbox">%s</div>'
            '<figcaption>%s</figcaption></figure>' % (s, cap))


def fig(name, cap):
    """본문 개요도 — docs/figures 의 SVG 를 본문 폭 그대로 인라인한다.

    부록의 제작도면과 달리 축소가 없으므로 글자가 그대로 읽힌다."""
    p = os.path.join(ROOT, "docs", "figures", name + ".svg")
    s = open(p, encoding="utf-8").read()
    s = re.sub(r'width="[\d.]+mm"\s+height="[\d.]+mm"', 'width="100%"', s, count=1)
    return ('<figure class="bodyfig"><div class="svgbox">%s</div>'
            '<figcaption>%s</figcaption></figure>' % (s, cap))


def png(name, cap, cls="half"):
    p = os.path.join(ENC, "png", name)
    b = base64.b64encode(open(p, "rb").read()).decode()
    return ('<figure class="%s"><img src="data:image/png;base64,%s"/>'
            '<figcaption>%s</figcaption></figure>' % (cls, b, cap))


def tbl(cols, rows, widths=None, cls=""):
    cg = ""
    if widths:
        cg = "<colgroup>%s</colgroup>" % "".join('<col style="width:%s">' % w for w in widths)
    h = "".join("<th>%s</th>" % c for c in cols)
    body = ""
    for r in rows:
        if len(r) == 1:
            body += '<tr class="grp"><td colspan="%d">%s</td></tr>' % (len(cols), r[0])
        else:
            body += "<tr>%s</tr>" % "".join("<td>%s</td>" % c for c in r)
    return '<table class="%s">%s<thead><tr>%s</tr></thead><tbody>%s</tbody></table>' % (cls, cg, h, body)


