■ 껍질이 굳지 않는다면 — 탈피 부전

새 껍질을 만드는 데는 물속의 무기질이 쓰입니다. 알칼리도가 낮은 물에서는 껍질이 제대로 굳지 못하고, 탈피를 시작했다가 마치지 못한 채 죽는 개체가 나옵니다. 이것을 탈피 부전이라고 부릅니다.

