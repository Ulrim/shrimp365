-- 염도 칸의 단위 주석 — **단위가 아직 확정되지 않았다**
--
-- 이 파일은 칸을 바꾸지 않는다. 주석만 단다. 그게 전부다.
--
-- 배경: water_quality_readings.salinity 에는 단위 주석이 없다(schema.sql:89).
--   천황수산 실데이터의 원본 헤더는 `염도(ppm)` 인데 값이 **30** 이다.
--   30 ppm 은 거의 담수이고 새우 양식 수조의 값일 수 없다. 반면 30 ppt/PSU 는
--   해수(약 35) 를 조금 희석한 값으로 바이오플락 양식에 딱 맞는다.
--   **데이터 제공자도 ppt/PSU 라고 단정하지 않았다**(평가서 6절 F-4, 8-2 ①).
--   사용자에게 질의한 상태이고 답을 기다리고 있다.
--
-- 그래서 **값을 환산하지 않고 칸도 바꾸지 않는다.** 환산은 되돌릴 수 없는 작업이고,
--   추측으로 한 번 곱해 두면 나중에 어느 행이 환산된 것인지 구분할 방법이 없다.
--   확정되기 전에 하는 환산은 데이터 정정이 아니라 데이터 훼손이다.
--   확정되면 그때 별도 마이그레이션으로 처리한다.
--
--   참고로 우리 앱은 이미 ppt 를 가정하고 있다 —
--   센서 수신 API 가 salinity 를 0~50 으로 받고 주석에 `ppt — 바닷물이 약 35` 라고
--   적어 뒀다(app/api/sensors/data/route.ts). **만약 단위가 정말 ppm 이라면
--   30,000 같은 실제 ppm 값은 이 범위 밖이라 조용히 버려진다.** 단위 확정이
--   주석 문제가 아니라 수신 동작 문제라는 뜻이다. 이것도 답을 받은 뒤 정리한다.
--
-- 실행 순서: 이 배치의 4번. 다른 파일과 독립이다.
-- 재실행 안전(COMMENT 는 덮어쓰기). Supabase SQL Editor 에서 실행한다(사람 몫).

COMMENT ON COLUMN public.water_quality_readings.salinity IS
  '⚠ 단위 미확정. 천황수산 원본 헤더는 ppm 이나 값의 크기(30)는 ppt/PSU 에 부합한다 — 데이터 제공자도 단정하지 않았고 농가·측정기 확인을 기다리는 중이다(평가서 F-4·8-2 ①). 확인 전에는 값을 환산하지 말 것. 앱(센서 수신 API)은 현재 ppt 를 가정해 0~50 범위로 받는다.';

-- 컬럼 주석은 PostgREST 의 스키마 문서에도 실린다. 캐시를 갱신해 둔다.
