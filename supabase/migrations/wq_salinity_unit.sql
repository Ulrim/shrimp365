-- 염도 칸의 단위 — **ppt(퍼밀, ‰) 로 확정됐다**
--
-- 2026-10-02 농가 확인: 30 퍼밀. 즉 ppt/PSU 다.
--
-- 경위: 천황수산 원본 헤더가 `염도(ppm)` 이고 값이 30 이었다. 30 ppm 은 거의
--   담수라 새우 양식 수조의 값일 수 없고, 30 ppt 는 해수(약 35)를 조금 희석한
--   값이라 바이오플락 양식에 맞는다. 데이터 제공자도 ppt 라고 단정하지 않고
--   `ppm (source label; unconfirmed)` 로 남겨 두었고(DataDictionary),
--   확인될 때까지 환산하지 않았다. 확인됐으므로 주석만 확정으로 바꾼다.
--
-- **값은 여전히 건드리지 않는다.** 원본이 담고 있던 수(30)가 곧 ppt 값이므로
--   환산할 것이 없다. 헤더 라벨만 틀렸던 것이다.
--
-- 앱 쪽도 이미 맞다 — 센서 수신 API 가 salinity 를 0~50 으로 받고 주석에
--   `ppt — 바닷물이 약 35` 라고 적어 두었다(app/api/sensors/data/route.ts).
--   ppm 이었다면 30,000 같은 값이 범위 밖이라 조용히 버려졌을 텐데, ppt 로
--   확정됐으므로 그 경로는 손댈 필요가 없다.
--
-- 실행 순서: 이 배치의 4번. 다른 파일과 독립이다.
-- 재실행 안전(COMMENT 는 덮어쓰기). Supabase SQL Editor 에서 실행한다(사람 몫).

COMMENT ON COLUMN public.water_quality_readings.salinity IS
  '염도(ppt = 퍼밀 ‰). 바닷물이 약 35. 2026-10-02 농가 확인으로 단위 확정 — 천황수산 원본 헤더는 ppm 이었으나 실제 값은 ppt 였다(헤더 오기). 환산하지 않고 원본 수를 그대로 쓴다.';

-- 컬럼 주석은 PostgREST 의 스키마 문서에도 실린다. 캐시를 갱신해 둔다.
NOTIFY pgrst, 'reload schema';
