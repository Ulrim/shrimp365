-- mrv_readings.measurement_basis — 그 kWh 를 **계량기가 쟀는가, 산식이 냈는가**.
--
-- ── 왜 ───────────────────────────────────────────────────────────────────────
-- `mrv_readings` 에는 이미 `source` 가 있다(mrv_readings_source.sql — device/manual/csv).
-- 그런데 그 열이 답하는 것은 **누가 넣었는가**이고, 지금 필요한 답은 **어떻게 얻었는가**다.
-- 둘은 직교한다 — 계량기를 읽어 손으로 적은 값도 manual 이고, 명판 정격으로 계산한 표를
-- CSV 로 올린 값도 csv 다. 창구가 같아도 증거의 종류가 다르다.
--
-- 이 구멍이 구체적으로 어떻게 터지는가. 실제로 받은 MRV 계산표(2026-08-01~10-16, 블로어
-- 2대, 1,848시간)는 모든 행에 이렇게 적어 두었다:
--
--     전력실측여부     = false
--     자료유형         = 가정 기반 계산 샘플(실측 아님)
--     배출량_자료유형  = 계산전력량×공표계수(실측·검증값 아님)
--     계산모델         = 장비별 ROUND(정격축출력 × 가정부하율 ÷ 가정효율 × 가동시간, 6)
--
-- 즉 그 kWh 는 계량기 지침이 아니라 **명판 정격에 가정 부하율·효율을 곱해 만든 수**다.
-- 그 파일을 지금 플랫폼에 올리면 계량기 실측과 **DB 에서 구분되지 않고**, EI·Scope2
-- 배출량·감축량이 그 계산값을 분자로 산출된 뒤 리포트가 그것을 아무 표시 없이 제시한다.
-- 검증기관이 가장 먼저 무너뜨릴 자리가 거기다 — 구분해 적을 칸이 없으면 "이 배출량의
-- 전력은 실측인가" 에 **플랫폼이 답할 수 없다.**
--
-- ── 값 ──────────────────────────────────────────────────────────────────────
--   metered    : 계량기 지침·실측(적산 지침의 차, 전력계가 올린 구간값).
--   calculated : 산식으로 계산한 값(정격 × 부하율 ÷ 효율 × 가동시간 등).
--   estimated  : 어림값(기억·경험으로 적은 수, 유사 기간에서 미룬 수).
--
-- `mrv_readings_source` 선례와 같은 모양의 CHECK 하나로 못박는다. 집합 밖의 값은 들어오지
-- 않으므로, 읽는 쪽은 "모르는 문자열" 분기를 가정하지 않아도 된다.
--
-- ── 기존 행은 null 로 남는다 (판단) ────────────────────────────────────────
-- **nullable 이고 default 가 없다.** 이미 쌓인 행은 null 그대로 둔다.
--
-- `metered` 로 채우고 싶은 유혹이 있다 — 지금까지의 계측값은 대개 전력계나 사람이 읽은
-- 지침이었으니까. 하지만 "대개" 는 증빙이 아니다. 그 행들이 실측이었다는 **기록은 어디에도
-- 없고**, 없는 사실을 만들어 적는 것은 이 플랫폼에서 빈 칸보다 나쁘다. 같은 판단을 이
-- 저장소가 이미 두 번 적어 두었다 — `mrv_api_key_revocation.sql` 의 `revoked_at`("SQL 직접
-- 수정으로 끊긴 행의 시각을 created_at 같은 값으로 메우지 않는다"), `mrv_kpi_config_org_scope.sql`
-- 의 `created_at`("2026-01-01 에 들어간 시드 행이 '오늘 등록됨' 으로 기록된다").
--
-- 그래서 **null = 미기재**다. 화면과 리포트가 그것을 "미기재" 로 적고, 실측으로 세지
-- 않으며, 실측이 아니라고도 단정하지 않는다(리포트의 「포함 품질 플래그」가 '칸이 없는
-- 것' 과 '빈 배열' 을 가르는 것과 같은 태도다 — lib/mrv/report-html.ts).
--
-- `source` 와 달리 `not null default` 를 걸지 않는 이유가 하나 더 있다. `source` 의 기본값
-- 'device' 는 **그때 참이었다**(그 열이 생기기 전에는 게이트웨이 경로밖에 없었다). 여기에는
-- 그런 참인 기본값이 없다.
--
-- ── 열 하나로 끝내고 플래그를 더하지 않는다 (판단) ─────────────────────────
-- 받은 표의 `전력실측여부 = false` 를 그대로 옮기면 불리언 한 칸이 되는데, 그러면
-- "실측이 아니다" 까지만 남고 **계산값인지 어림값인지**가 사라진다. 두 칸(불리언 + 종류)을
-- 두면 한쪽만 채워지는 날 서로 모순되는 행이 생긴다(`revoked`/`revoked_at` 에 제약을 걸지
-- 않은 이유와 같은 종류의 문제다). 그래서 뜻이 하나로 모이는 열 하나만 둔다.
--
-- ── 색인을 만들지 않는다 (판단) ────────────────────────────────────────────
-- `source` 때는 (org_id, source, time) 색인을 만들었다. 여기서는 만들지 않는다 —
-- 이 열로 거르는 질의가 없기 때문이다. 자료유형 집계는 기간 질의로 이미 읽어 온 행을
-- 메모리에서 나눠 센다(lib/mrv/kpi-service.ts). readings 는 시계열이라 행이 가장 많이
-- 쌓이는 표이고, 쓰이지 않는 색인은 그 표의 모든 수집 요청에 비용만 더한다. 나중에
-- "실측이 아닌 계측값만 뽑아 보기" 가 필요해지면 그때 그 질의의 모양대로 만들면 된다.
--
-- ⚠ 실행 순서. 이 마이그레이션을 **배포 전에** 돌려야 한다. 새 코드는 계측값을 저장할 때
-- 이 열을 함께 보내고 KPI 조회가 이 열을 함께 읽으므로, 열이 없는 DB 에 새 코드를 띄우면
-- PostgREST 가 그 열을 모른다며 수집 요청과 KPI 조회를 거절한다. `mrv_readings_source.sql`
-- 과 같은 이유로 그 실패를 조용히 넘기게 만들지 않았다 — 자료유형 없이 저장된 전력은
-- 나중에 되짚을 수 없고, 그 사실이 조용히 묻히는 쪽이 요청 하나가 실패하는 쪽보다 훨씬
-- 비싸다.
--
-- 멱등이다. 여러 번 실행해도 안전하다.
-- 되돌리기: alter table public.mrv_readings drop column if exists measurement_basis;
-- (열을 지우면 그때까지 기록한 자료유형 구분이 사라진다.)
-- ---------------------------------------------------------------------------

alter table public.mrv_readings
  add column if not exists measurement_basis text;

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'ck_mrv_readings_measurement_basis'
  ) then
    alter table public.mrv_readings
      add constraint ck_mrv_readings_measurement_basis
      check (measurement_basis in ('metered', 'calculated', 'estimated'));
  end if;
end $$;

comment on column public.mrv_readings.measurement_basis is
  '이 값을 어떻게 얻었는가. metered=계량기 지침·실측, calculated=산식으로 계산(정격 × '
  '부하율 ÷ 효율 × 가동시간 등), estimated=어림값. **null 은 「미기재」이며 실측을 뜻하지 '
  '않는다** — 이 열이 생기기 전에 저장된 행이 전부 null 이고, 그 행들이 실측이었다는 '
  '기록은 없으므로 추정으로 메우지 않았다. source 열과 직교한다: source 는 「누가 '
  '넣었는가」(device/manual/csv), 이 열은 「어떻게 얻었는가」다 — 계산값도 CSV 로 들어온다.';
