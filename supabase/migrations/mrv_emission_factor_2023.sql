-- 전력 배출계수를 공식 최신값(2023년도분 0.4173)으로 바꾼다 + 사용 중단 표시 추가.
--
-- ── 왜 ───────────────────────────────────────────────────────────────────────
-- 기존 시드 행은 `0.4594 / year 2024 / KR-GRID-2024.1` 이었다. **값-연도 조합이
-- 공식 출처와 맞지 않는다.** 0.4594 자체는 한국에너지공단 EG-TIPS·배출권거래제
-- 외부사업 감축량 계산기에 `0.459411 tCO2-eq/MWh` 로 실재하지만, 같은 출처 안에서
-- "국가고유 11년" 과 "17년" 이 상충해 승인연도가 확정되지 않으며, **2024년 값이라는
-- 근거는 어디에도 없다**(2024년 승인분 = 2020~2022 평균 = 0.4541).
--
-- 현재 유효한 공식값은 **2023년도 단년도 계수 0.4173 tCO2eq/MWh** 다. 기후에너지환경부가
-- 국가 온실가스 통계 관리위원회 심의를 거쳐 2025-12-17 확정, 12-18 공표했다. 같은 공표에
-- CO2 만 기준 0.4149 가 함께 나오므로, 이 행이 **CO2e 기준**임을 source 에 못박는다.
--
-- ⚠ 검증 한계(반드시 읽을 것): 이 값은 기후에너지환경부 보도자료와 복수 언론 보도의
-- 교차 확인이며, **GIR 공표 원문 PDF 를 직접 열어 확인한 것이 아니다**(작업 환경에서
-- 해당 호스트 조회가 되지 않았다). 상용 증빙에 쓰기 전 사람이 GIR 원문 1건으로
-- ① 수치 ② CO2e 기준 ③ 2023년도 단년도분 ④ 공표일을 확인하고, 그 문서명·URL 을
-- 아래 source 문자열에 보강할 것.
--
-- ── 기존 행을 고치지 않는 이유 ───────────────────────────────────────────────
-- 리포트 PDF 는 `mrv_reports.emission_factor_id` 로 **활성 조인**해 계수 행의
-- version·source·year 를 그대로 인쇄한다(`lib/mrv/mrv-report-loader.ts`). 즉 기존 행의
-- source 나 year 를 고치면 **이미 발행된 리포트의 인쇄 내용이 사후에 바뀐다** — 증빙
-- 무결성이 깨지는 바로 그 일이다. 그래서 이 마이그레이션은 **더하기만 한다**:
--   · 새 계수 행을 추가하고,
--   · `deprecated_at` 열을 새로 만들어 옛 행에 표시한다.
-- `deprecated_at` 은 **활성 계수 선택에서만** 그 행을 빼고, 인쇄되는 세 열은 건드리지
-- 않으므로 과거 리포트의 출력은 한 글자도 달라지지 않는다.
--
-- ── year 와 effective_from 은 다른 것이다 ────────────────────────────────────
-- 이 혼동이 애초의 오류를 만들었으므로 규약을 못박는다.
--   · `year`           = 계수가 **설명하는 데이터 연도**(2023년 전력 계통의 배출 수준)
--   · `effective_from` = 이 플랫폼이 **새 리포트에 이 계수를 쓰기 시작하는 시점**
-- 활성 계수 판정은 `effective_from desc limit 1` 이다(`mrv-report-service.ts`). 2023년도
-- 계수는 2025-12-18 에 공표됐으므로 그날부터 활성이다 — `effective_from` 에 2023-01-01 을
-- 넣으면 공표도 되기 전에 쓴 것이 되고, 옛 행(2024-01-01)보다 앞서 활성이 되지도 않는다.
--
-- ── 갱신 주기가 바뀌었다 ─────────────────────────────────────────────────────
-- 2025년 12월부터 전력배출계수 갱신 주기가 **3년 → 1년**으로 단축됐고, 3년 평균이 아니라
-- **단년도 계수를 매년 12월에 공표**한다. 계수는 '거의 고정' 이 아니라 **매년 갱신되는
-- 운영 자산**이다. 매년 12월 공표를 확인해 새 행을 추가하는 일이 운영 캘린더에 들어가야
-- 한다(이 마이그레이션처럼 더하기만 하면 과거 리포트는 영향받지 않는다).
--
-- 과거분 소급 재계산은 하지 않는다. 배출권거래제가 "할당 시 사용한 계수를 정산까지 동일
-- 적용" 하는 것과 같은 원칙이고, 이 스키마의 append-only + 리포트의 계수 참조가 그 구조다.
--
-- 멱등이다. 여러 번 실행해도 안전하다.
-- ---------------------------------------------------------------------------

-- ① 사용 중단 표시 열. 값이 있으면 '활성 계수 자동 선택'에서 제외된다.
--    명시적으로 지정한 경우(과거 리포트 재생성)에는 여전히 쓸 수 있어야 하므로
--    행을 지우거나 숨기지 않는다.
alter table public.mrv_emission_factors
  add column if not exists deprecated_at timestamptz;

comment on column public.mrv_emission_factors.deprecated_at is
  '사용 중단 시점. 비어 있지 않으면 활성 계수 자동 선택에서 제외한다. 과거 리포트가 '
  '참조하는 행일 수 있으므로 삭제하지 않고 이 열로만 표시한다.';

-- ② 2023년도 공식 계수.
insert into public.mrv_emission_factors
  (id, factor_tco2e_per_mwh, source, year, version, effective_from)
values (
  'ef-kr-grid-2023',
  0.4173,
  '기후에너지환경부 국가 온실가스 통계 관리위원회 확정 2023년도 국가 전력배출계수 '
    || '(2025-12-17 확정 · 2025-12-18 공표) · CO2e 기준 · 단년도 평균 '
    || '[원문 PDF 대조 전 — GIR 공표 문서명·URL 보강 필요]',
  2023,
  'KR-GRID-2023',
  timestamptz '2025-12-18 00:00:00+09'
)
on conflict (version) do nothing;

-- ③ 옛 행을 사용 중단으로 표시한다. value·year·version·source 는 건드리지 않는다
--    (이미 발행된 리포트가 인쇄하는 값이다).
update public.mrv_emission_factors
   set deprecated_at = timestamptz '2025-12-18 00:00:00+09'
 where version = 'KR-GRID-2024.1'
   and deprecated_at is null;
